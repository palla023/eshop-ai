-- Run this in the Supabase SQL editor after creating a project.
-- Auth users live in auth.users. App roles and profile data live here.

create table if not exists public.user_profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  email text unique not null,
  name text not null,
  role text not null default 'user' check (role in ('admin', 'user')),
  is_active boolean not null default true,
  profile_pic text default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.user_profiles enable row level security;

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.user_profiles
    where email = auth.jwt() ->> 'email'
      and role = 'admin'
  );
$$;

grant execute on function public.is_admin() to authenticated;

create policy "Users can read their own profile"
  on public.user_profiles
  for select
  to authenticated
  using (auth.uid() = id or email = auth.jwt() ->> 'email');

drop policy if exists "Admins can read all profiles" on public.user_profiles;
create policy "Admins can read all profiles"
  on public.user_profiles
  for select
  to authenticated
  using (public.is_admin());

create policy "Users can insert their own profile"
  on public.user_profiles
  for insert
  to authenticated
  with check (auth.uid() = id);

-- Live user_profiles.id is bigint; auth.uid() is uuid. Never compare the two
-- (22P02). Match the signed-in email instead, same as address RLS.
drop policy if exists "Users can update their own profile" on public.user_profiles;
create policy "Users can update their own profile"
  on public.user_profiles
  for update
  to authenticated
  using (email = auth.jwt() ->> 'email')
  with check (email = auth.jwt() ->> 'email');

drop policy if exists "Admins can insert profiles" on public.user_profiles;
create policy "Admins can insert profiles"
  on public.user_profiles
  for insert
  to authenticated
  with check (public.is_admin());

drop policy if exists "Admins can update all profiles" on public.user_profiles;
create policy "Admins can update all profiles"
  on public.user_profiles
  for update
  to authenticated
  using (public.is_admin())
  with check (public.is_admin());

drop policy if exists "Admins can delete profiles" on public.user_profiles;
create policy "Admins can delete profiles"
  on public.user_profiles
  for delete
  to authenticated
  using (public.is_admin());

create or replace function public.protect_user_profile_fields()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if public.is_admin() then
    return NEW;
  end if;
  NEW.role := OLD.role;
  NEW.is_active := OLD.is_active;
  NEW.email := OLD.email;
  return NEW;
end;
$$;

drop trigger if exists protect_user_profile_fields on public.user_profiles;
create trigger protect_user_profile_fields
  before update on public.user_profiles
  for each row
  execute function public.protect_user_profile_fields();

