  on public.categories
  for select
  to authenticated
  using (true);

create policy "Authenticated users can insert categories"
  on public.categories
  for insert
  to authenticated
  with check (true);

-- Live project uses bigint ids on user_profiles and address (not auth UUIDs).
-- Do not compare auth.uid() to those columns; that raises 22P02.

create table if not exists public.address (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.user_profiles (id) on delete cascade,
  name text not null,
  phone text not null,
  address_line text not null,
  city text not null,
  state text not null,
  postal_code text not null,
  is_default boolean not null default false,
  created_at timestamptz not null default now()
);

alter table public.address
  add column if not exists is_default boolean not null default false;

alter table public.address enable row level security;

drop policy if exists "Users can read their own addresses" on public.address;
drop policy if exists "Users can insert their own addresses" on public.address;
drop policy if exists "Users can update their own addresses" on public.address;
drop policy if exists "Users can delete their own addresses" on public.address;

create policy "Users can read their own addresses"
  on public.address
  for select
  to authenticated
  using (
    user_id = (
      select p.id
      from public.user_profiles p
      where p.email = auth.jwt() ->> 'email'
      limit 1
    )
    or public.is_admin()
  );

create policy "Users can insert their own addresses"
  on public.address
  for insert
  to authenticated
  with check (
    user_id = (
      select p.id
      from public.user_profiles p
      where p.email = auth.jwt() ->> 'email'
      limit 1
    )
  );

create policy "Users can update their own addresses"
  on public.address
  for update
  to authenticated
  using (
    user_id = (
      select p.id
      from public.user_profiles p
      where p.email = auth.jwt() ->> 'email'
      limit 1
    )
  )
  with check (
    user_id = (
      select p.id
      from public.user_profiles p
      where p.email = auth.jwt() ->> 'email'
      limit 1
    )
  );

create policy "Users can delete their own addresses"
  on public.address
  for delete
  to authenticated
  using (
    user_id = (
      select p.id
      from public.user_profiles p
      where p.email = auth.jwt() ->> 'email'
      limit 1
    )
  );

